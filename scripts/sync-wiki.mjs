// Mirrors docs/**/*.md and history/**/*.md into the GitHub wiki repo.
// Usage: node scripts/sync-wiki.mjs <wiki-dir>
// <wiki-dir> must be a clone of https://github.com/OWNER/REPO.wiki.git
// Also copies wiki-assets/ into <wiki-dir>/assets/.
import {
	copyFileSync,
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import path from "node:path";

const wikiDir = process.argv[2];
if (!(wikiDir && existsSync(path.join(wikiDir, ".git")))) {
	console.error(
		"Usage: node scripts/sync-wiki.mjs <wiki-dir>  (must be a git clone of the wiki repo)",
	);
	process.exit(1);
}

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const PREFIXES = { docs: "Docs", history: "History" };
const W = "\n";

function encode(prefix, relpath) {
	const parts = relpath.split(path.sep).join("/").split("/");
	const stem = [...parts.slice(0, -1), parts[parts.length - 1].replace(/\.md$/u, "")].join("-");
	return `${prefix}-${stem
		.replace(/[^A-Za-z0-9._-]+/gu, "-")
		.replace(/-{2,}/gu, "-")
		.replace(/^-|-$/gu, "")}.md`;
}

// Collect sources: filename -> { src, relpath (with folder prefix) }
const generated = new Map();
for (const [folder, prefix] of Object.entries(PREFIXES)) {
	const base = path.join(root, folder);
	if (!existsSync(base)) continue;
	const walk = (dir) => {
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			const full = path.join(dir, entry.name);
			if (entry.isDirectory()) walk(full);
			else if (entry.name.endsWith(".md")) {
				const rel = path.relative(base, full);
				generated.set(encode(prefix, rel), {
					src: full,
					folder,
					rel: rel.split(path.sep).join("/"),
				});
			}
		}
	};
	walk(base);
}

// Remove mirrored pages that no longer exist in the source tree.
let removed = 0;
for (const entry of readdirSync(wikiDir)) {
	if (/^(Docs|History)-.*\.md$/u.test(entry) && !generated.has(entry)) {
		rmSync(path.join(wikiDir, entry));
		removed++;
	}
}

// Copy current files in, prepending a provenance breadcrumb to markdown.
let copied = 0;
for (const [name, { src, folder, rel }] of generated) {
	const body = readFileSync(src, "utf8");
	const crumb = `> 📄 Mirror of \`${folder}/${rel}\` · part of [[Site-Index]] · edit the source, not this page\n\n`;
	writeFileSync(path.join(wikiDir, name), crumb + body);
	copied++;
}

// Generate Site-Index.md: every mirrored page grouped by source folder / month.
const groups = new Map(); // group label -> [{ name, rel }]
for (const [name, { folder, rel }] of generated) {
	let group;
	if (folder === "docs") {
		const seg = rel.split("/");
		group = seg.length > 1 ? `docs — ${seg[0]}` : "docs — (root)";
	} else {
		const m = /^(\d{4}-\d{2})/u.exec(rel);
		group = m ? `history — ${m[1]}` : "history — (undated)";
	}
	if (!groups.has(group)) groups.set(group, []);
	groups.get(group).push({ name: name.replace(/\.md$/u, ""), rel });
}
const sortedGroups = [...groups.entries()].sort((a, b) => {
	const docsA = a[0].startsWith("docs") ? 0 : 1;
	const docsB = b[0].startsWith("docs") ? 0 : 1;
	if (docsA !== docsB) return docsA - docsB;
	return a[0].localeCompare(b[0]);
});
const indexLines = [
	"# Site Index",
	"",
	`> Auto-generated by \`scripts/sync-wiki.mjs\`. ${generated.size} mirrored pages from the repo's \`docs/\` and \`history/\` folders.`,
	"",
	"> 📄 Every page here is a CI-generated mirror. Edit the source file in the repo; do not edit these pages directly.",
	"",
	"## Jump to",
	"",
	...sortedGroups.map(
		([g]) =>
			`- [${g}](#${g
				.replace(/\s+/gu, "-")
				.replace(/[^\w-]/gu, "")
				.toLowerCase()})`,
	),
	"",
];
for (const [group, items] of sortedGroups) {
	items.sort((a, b) => a.rel.localeCompare(b.rel));
	indexLines.push(
		`## ${group} (${items.length})`,
		"",
		"<details>",
		`<summary>${items.length} pages</summary>`,
		"",
	);
	for (const item of items) indexLines.push(`- [[${item.name}]] — \`${item.rel}\``);
	indexLines.push("", "</details>", "");
}
writeFileSync(path.join(wikiDir, "Site-Index.md"), indexLines.join(W));

// Copy wiki-assets/ into the wiki repo's assets/ folder.
let assets = 0;
const assetsSrc = path.join(root, "wiki-assets");
const assetsDst = path.join(wikiDir, "assets");
if (existsSync(assetsSrc)) {
	mkdirSync(assetsDst, { recursive: true });
	for (const entry of readdirSync(assetsSrc)) {
		if (/\.(svg|png)$/iu.test(entry)) {
			copyFileSync(path.join(assetsSrc, entry), path.join(assetsDst, entry));
			assets++;
		}
	}
}

console.log(
	`wiki-sync: ${copied} mirrored, ${removed} removed, Site-Index.md written, ${assets} assets copied`,
);
