#!/usr/bin/env node
// Generates the reference pages under docs/developer/ from the source of truth:
//   api-reference.md       <- server/server.js mounts + server/routes/*.js
//   database-reference.md  <- prisma/schema.prisma + prisma/migrations/
// Usage: node scripts/docs/generate-reference.mjs [--check]
//   --check  exit 1 if a generated page is out of date (for CI), write nothing.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
const HEADER = (sources) =>
	`<!-- Generated by scripts/docs/generate-reference.mjs from ${sources}. Do not edit by hand; run \`pnpm run docs:generate\`. -->\n\n`;

// ---------------------------------------------------------------- API routes

// Splits "a, b(c, d), [e]" at top-level commas.
function splitArgs(text) {
	const parts = [];
	let depth = 0;
	let quote = null;
	let current = "";
	for (const ch of text) {
		if (quote) {
			current += ch;
			if (ch === quote) quote = null;
			continue;
		}
		if (ch === '"' || ch === "'" || ch === "`") quote = ch;
		else if ("([{".includes(ch)) depth += 1;
		else if (")]}".includes(ch)) depth -= 1;
		if (ch === "," && depth === 0) {
			parts.push(current.trim());
			current = "";
		} else current += ch;
	}
	if (current.trim()) parts.push(current.trim());
	return parts;
}

// Returns the argument text of a call starting at `start` (index of "(").
function callArgs(source, start) {
	let depth = 0;
	for (let i = start; i < source.length; i += 1) {
		if (source[i] === "(") depth += 1;
		else if (source[i] === ")") {
			depth -= 1;
			if (depth === 0) return source.slice(start + 1, i);
		}
	}
	return "";
}

function describeMiddleware(args, aliases) {
	const info = { auth: "public", roles: [], limits: [], other: [] };
	const visit = (arg) => {
		const name = arg.trim();
		if (aliases.has(name)) return aliases.get(name).forEach(visit);
		if (name.startsWith("[")) return splitArgs(name.slice(1, -1)).forEach(visit);
		if (name === "requireAuth") info.auth = "required";
		else if (name === "optionalAuth" && info.auth === "public") info.auth = "optional";
		else if (name.startsWith("allowRoles(")) {
			info.auth = "required";
			info.roles.push(...[...name.matchAll(/["']([\w-]+)["']/g)].map((m) => m[1]));
		} else if (/limiter/i.test(name)) info.limits.push(name.replace(/\(.*$/s, ""));
		else if (/^upload\b|\.single\(|\.array\(|\.fields\(/.test(name)) info.other.push("file upload");
	};
	args.forEach(visit);
	return info;
}

function parseRouter(file) {
	const source = read(file);
	const aliases = new Map();
	for (const m of source.matchAll(/^const (\w+)\s*=\s*(allowRoles\([^)]*\)|\[[^\]]*\])\s*;/gm)) {
		aliases.set(m[1], [m[2]]);
	}
	const global = [];
	const routes = [];
	const re = /\brouter\.(use|get|post|put|patch|delete|all)\s*\(/g;
	for (let m = re.exec(source); m; m = re.exec(source)) {
		const args = splitArgs(callArgs(source, m.index + m[0].length - 1));
		if (m[1] === "use") {
			if (args[0] && !/^["'`]/.test(args[0])) global.push(...args);
			continue;
		}
		const pathArg = args[0] || "";
		if (!/^["'`]/.test(pathArg)) continue;
		const middleware = describeMiddleware([...global, ...args.slice(1, -1)], aliases);
		const last = args.at(-1) || "";
		const handler = /=>|^async\b|^function\b/.test(last) ? "inline" : last.replace(/\s+/g, " ");
		routes.push({ method: m[1].toUpperCase(), path: pathArg.slice(1, -1), handler, ...middleware });
	}
	return routes;
}

function apiReference() {
	const server = read("server/server.js");
	const imports = new Map(
		[...server.matchAll(/^import (\w+) from "\.\/routes\/(\w+\.js)";/gm)].map((m) => [
			m[1],
			`server/routes/${m[2]}`,
		]),
	);
	const mounts = [...server.matchAll(/^app\.use\("(\/api[^"]*)",\s*(?:[^;]*?,\s*)?(\w+)\);/gm)]
		.map((m) => ({ base: m[1], file: imports.get(m[2]) }))
		.filter((m) => m.file);
	const direct = [...server.matchAll(/^app\.(get|post|head)\("([^"]+)"/gm)].map(
		(m) => `${m[1].toUpperCase()} ${m[2]}`,
	);

	let total = 0;
	const sections = mounts.map(({ base, file }) => {
		const routes = parseRouter(file);
		total += routes.length;
		const rows = routes.map((r) => {
			const notes = [...r.limits, ...r.other].join(", ");
			const roles = r.roles.length ? [...new Set(r.roles)].join(", ") : "";
			const route = `${base}${r.path === "/" ? "" : r.path}`;
			return `| ${r.method} | \`${route}\` | ${r.auth} | ${roles} | ${notes} | \`${r.handler}\` |`;
		});
		return [
			`## \`${base}\``,
			"",
			`Source: [${file}](../../${file})`,
			"",
			"| Method | Path | Auth | Roles | Limits / notes | Handler |",
			"| --- | --- | --- | --- | --- | --- |",
			...rows,
			"",
		].join("\n");
	});

	return [
		HEADER("server/server.js and server/routes/*.js"),
		"# API reference",
		"",
		`${total} HTTP endpoints across ${mounts.length} routers. All JSON; authenticated calls send`,
		"`Authorization: Bearer <jwt>` (see [security.md](security.md)). **Auth**: `public` = no token,",
		"`optional` = token used when present, `required` = 401 without a valid, non-revoked session.",
		"**Roles**: when listed, other roles get 403. Realtime (`/ws`, SSE) is described in",
		"[architecture.md](architecture.md#realtime).",
		"",
		"Server-level endpoints in `server/server.js`: " +
			direct.map((d) => `\`${d}\``).join(", ") +
			".",
		"",
		...sections,
	].join("\n");
}

// ------------------------------------------------------------------ database

function databaseReference() {
	const schema = read("prisma/schema.prisma");
	const models = [...schema.matchAll(/^model (\w+) \{\n([\s\S]*?)^\}/gm)].map((m) => {
		const body = m[2].split("\n").map((l) => l.trim());
		const table = (body.find((l) => l.startsWith("@@map(")) || "").match(/"([^"]+)"/)?.[1] || m[1];
		const fields = body
			.filter((l) => l && !l.startsWith("//") && !l.startsWith("@@"))
			.map((l) => {
				const [name, type, ...rest] = l.split(/\s+/);
				const attrs = rest.join(" ");
				const notes = [];
				if (/@id\b/.test(attrs)) notes.push("PK");
				if (/@unique\b/.test(attrs)) notes.push("unique");
				const def = attrs.match(/@default\(((?:[^()]|\([^()]*\))*)\)/);
				if (def) notes.push(`default ${def[1]}`);
				const rel = attrs.match(/@relation\([^)]*fields:\s*\[([^\]]+)\]/);
				if (rel) notes.push(`FK via ${rel[1]}`);
				return { name, type, notes: notes.join(", ") };
			});
		const indexes = body
			.filter((l) => /^@@(index|unique|id)\(/.test(l))
			.map((l) => l.replace(/,\s*map:\s*"[^"]*"/, "").replace(/\s+/g, " "));
		return { name: m[1], table, fields, indexes };
	});
	const enums = [...schema.matchAll(/^enum (\w+) \{\n([\s\S]*?)^\}/gm)].map(
		(m) =>
			`- \`${m[1]}\`: ${m[2]
				.split("\n")
				.map((l) => l.trim())
				.filter((l) => l && !l.startsWith("//"))
				.join(", ")}`,
	);
	const migrations = fs
		.readdirSync(path.join(root, "prisma/migrations"))
		.filter((d) => /^\d{14}_/.test(d))
		.sort();

	const sections = models.map((model) =>
		[
			`### ${model.name} → \`${model.table}\``,
			"",
			"| Column | Type | Notes |",
			"| --- | --- | --- |",
			...model.fields.map((f) => `| ${f.name} | \`${f.type}\` | ${f.notes} |`),
			...(model.indexes.length
				? ["", `Indexes: ${model.indexes.map((i) => `\`${i}\``).join(", ")}`]
				: []),
			"",
		].join("\n"),
	);

	return [
		HEADER("prisma/schema.prisma and prisma/migrations/"),
		"# Database reference",
		"",
		`PostgreSQL via Prisma 6. ${models.length} models, ${enums.length} enums, ${migrations.length} migrations.`,
		"Schema changes ship **only** as migrations (`prisma migrate deploy` runs on every Render deploy);",
		"see [database.md](database.md) for the workflow and safety rules.",
		"",
		"## Migrations (applied in this order)",
		"",
		...migrations.map((m) => `- \`${m}\``),
		"",
		...(enums.length ? ["## Enums", "", ...enums, ""] : []),
		"## Models",
		"",
		models
			.map((m) => `[${m.name}](#${m.name.toLowerCase()}--${m.table.toLowerCase()})`)
			.join(" · "),
		"",
		...sections,
	].join("\n");
}

// ------------------------------------------------------- environment variables

function listFiles(dir, exts) {
	const out = [];
	for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
		const rel = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			if (!["node_modules", "dist", "__mocks__"].includes(entry.name))
				out.push(...listFiles(rel, exts));
		} else if (exts.some((ext) => entry.name.endsWith(ext))) out.push(rel);
	}
	return out;
}

function envReference() {
	const used = new Map();
	for (const dir of ["server", "shared", "src", "scripts"]) {
		for (const file of listFiles(dir, [".js", ".mjs", ".jsx"])) {
			const source = read(file);
			for (const m of source.matchAll(/(?:process\.env|import\.meta\.env)\.([A-Z][A-Z0-9_]+)/g)) {
				if (!used.has(m[1])) used.set(m[1], new Set());
				used
					.get(m[1])
					.add(
						dir === "src" ? "frontend (build time)" : file.split(path.sep).slice(0, 2).join("/"),
					);
			}
		}
	}
	const example = new Set(
		[...read(".env.example").matchAll(/^([A-Z][A-Z0-9_]+)=/gm)].map((m) => m[1]),
	);
	const render = new Set(
		[...read("render.yaml").matchAll(/- key: ([A-Z][A-Z0-9_]+)/g)].map((m) => m[1]),
	);
	const rows = [...used.keys()].sort().map((name) => {
		const where = [...used.get(name)].sort();
		const shown = where.slice(0, 3).join(", ") + (where.length > 3 ? ` +${where.length - 3}` : "");
		return `| \`${name}\` | ${example.has(name) ? "✓" : ""} | ${render.has(name) ? "✓" : ""} | ${shown} |`;
	});
	return [
		HEADER(
			"process.env / import.meta.env reads in server/, shared/, src/, scripts/, plus .env.example and render.yaml",
		),
		"# Environment variable reference",
		"",
		`${used.size} variables are read by the code. Which ones you need, and safe local values, are in`,
		"[configuration.md](configuration.md). **Never put a value in docs, commits or reports** — only names.",
		"`.env.example` / `render.yaml` columns show where a variable is declared; a variable in neither falls",
		"back to its in-code default.",
		"",
		"| Variable | .env.example | render.yaml | Read in |",
		"| --- | --- | --- | --- |",
		...rows,
		"",
	].join("\n");
}

// --------------------------------------------------------------------- write

const outputs = {
	"docs/developer/api-reference.md": apiReference(),
	"docs/developer/database-reference.md": databaseReference(),
	"docs/developer/env-reference.md": envReference(),
};
const check = process.argv.includes("--check");
let stale = 0;
for (const [file, content] of Object.entries(outputs)) {
	const target = path.join(root, file);
	const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
	if (current === content) continue;
	stale += 1;
	if (check) console.error(`out of date: ${file}`);
	else {
		fs.mkdirSync(path.dirname(target), { recursive: true });
		fs.writeFileSync(target, content);
		console.log(`wrote ${file}`);
	}
}
if (check && stale) process.exit(1);
if (!stale) console.log("docs reference up to date");
